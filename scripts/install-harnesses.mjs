import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { dirname, join, relative, resolve, sep } from "node:path"
import { HARNESS_TARGETS } from "../src/portability/contract.mjs"

/**
 * Each host pulls the shared rules in with its own import syntax rather than receiving a copy.
 * A copied AGENTS.md would silently diverge the first time the source changes; an import cannot.
 */
const IMPORT_SYNTAX = {
  "claude-code": "@AGENTS.md",
  "claude-skills": null,
  "opencode-project": null,
  codex: null,
  "agents-md": null,
  cursor: "@AGENTS.md",
  windsurf: "@AGENTS.md",
  "gemini-cli": "@./AGENTS.md",
  "github-copilot": "AGENTS.md is the instruction file for this repository; read it before acting.",
  cline: "@AGENTS.md",
  aider: "AGENTS.md is the instruction file for this repository; read it before acting.",
  "agent-skills": null,
  "generic-markdown": null,
  opencode: null,
}

const NOTE = "This file is generated by `npm run harnesses` from AGENTS.md. Do not edit it here."

function writeFile(sourceRoot, relativePath, content) {
  const target = resolve(join(sourceRoot, relativePath))
  mkdirSync(dirname(target), { recursive: true })
  writeFileSync(target, content, "utf-8")
  return relativePath
}

function copyTree(sourceRoot, from, to) {
  const source = resolve(sourceRoot, from)
  const destinationRoot = resolve(sourceRoot, to)
  if (!existsSync(source)) return []
  if (source === destinationRoot) return []
  const written = []
  for (const entry of readdirSync(source, { withFileTypes: true })) {
    if (entry.name === "node_modules" || entry.name.startsWith(".")) continue
    if (entry.isDirectory()) {
      written.push(...copyTree(sourceRoot, resolve(source, entry.name), `${to}/${entry.name}`))
      continue
    }
    if (!entry.isFile()) continue
    const destination = `${to}/${entry.name}`
    writeFile(sourceRoot, destination, readFileSync(join(source, entry.name), "utf-8"))
    written.push(destination)
  }
  return written
}

function pointerBody(target) {
  const syntax = IMPORT_SYNTAX[target.id]
  if (syntax === null) return null
  const body = `# Overgeared Skills\n\n${NOTE}\n\n${syntax}\n`
  if (target.id === "cursor") {
    return `---\ndescription: Overgeared Skills orchestration, skills, and memory rules\nalwaysApply: true\n---\n\n${body}`
  }
  if (target.id === "windsurf") {
    return `---\ntrigger: always_on\ndescription: Overgeared Skills orchestration, skills, and memory rules\n---\n\n${body}`
  }
  return body
}

function isProjectScoped(target) {
  return target.configRoot.startsWith("<repository-root>") || target.id === "claude-skills"
}

/**
 * The directory a project-scoped harness reads from, relative to the repository root. A layout
 * path is only correct relative to that base, which is why `rules/gentjin.mdc` becomes
 * `.cursor/rules/gentjin.mdc` rather than landing at the root.
 */
function baseDir(target) {
  if (target.configRoot === "<repository-root>") return ""
  const stripped = target.configRoot.replace("<repository-root>", "").replace(/^\/+/, "")
  if (stripped === ".claude") return ".claude"
  return stripped
}

function under(base, relativePath) {
  return base ? `${base}/${relativePath}` : relativePath
}

/**
 * Writes the project-local layout each selected harness expects. AGENTS.md stays the single
 * source of truth; hosts that cannot import it receive a generated copy instead.
 */
export function installHarnesses({ sourceRoot = process.cwd(), harnessIds } = {}) {
  const unknown = (harnessIds ?? []).filter((id) => !HARNESS_TARGETS.some((h) => h.id === id))
  if (unknown.length > 0) throw new Error(`unknown harness id(s): ${unknown.join(", ")}`)

  const selected = harnessIds?.length
    ? HARNESS_TARGETS.filter((h) => harnessIds.includes(h.id))
    : HARNESS_TARGETS

  const agentsBody = readFileSync(join(sourceRoot, "AGENTS.md"), "utf-8")
  const written = []
  const skipped = []

  for (const target of selected) {
    if (!isProjectScoped(target)) {
      skipped.push(`${target.id} installs into ${target.configRoot}, not the repository`)
      continue
    }

    const { layout } = target
    const base = baseDir(target)

    if (layout.instructions) {
      const destination = under(base, layout.instructions)
      if (destination !== "AGENTS.md") {
        const pointer = pointerBody(target)
        written.push(writeFile(sourceRoot, destination, pointer ?? agentsBody))
      }
    }

    if (layout.commands) {
      written.push(...copyTree(sourceRoot, "command", under(base, layout.commands.replace(/\/$/, ""))))
    }

    if (layout.skills) {
      written.push(...copyTree(sourceRoot, "skills", under(base, layout.skills.replace(/\/$/, ""))))
    }
  }

  return {
    harnesses: selected.map((h) => h.id),
    written: written.sort(),
    skipped,
  }
}

export function relativeToRoot(sourceRoot, path) {
  return relative(resolve(sourceRoot), resolve(path)).split(sep).join("/")
}

if (process.argv[1] && process.argv[1].endsWith("install-harnesses.mjs")) {
  const requested = process.argv.slice(2).filter((arg) => !arg.startsWith("-"))
  const result = installHarnesses({ harnessIds: requested.length ? requested : undefined })
  for (const note of result.skipped) console.log(`skipped ${note}`)
  console.log(`harnesses: ${result.harnesses.join(", ")}`)
  console.log(`files written: ${result.written.length}`)
}